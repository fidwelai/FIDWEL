drop policy if exists "Users can view their own profile" on public.profiles;
create policy "Users can view their own profile"
on public.profiles for select to authenticated
using (id = auth.uid());

drop policy if exists "Users can update their own profile" on public.profiles;
create policy "Users can update their own profile"
on public.profiles for update to authenticated
using (id = auth.uid())
with check (id = auth.uid());

drop policy if exists "Anyone can browse categories" on public.categories;
create policy "Anyone can browse categories"
on public.categories for select to anon, authenticated
using (true);

drop policy if exists "Users can view their vendor profile" on public.vendor_profiles;
create policy "Users can view their vendor profile"
on public.vendor_profiles for select to authenticated
using (user_id = auth.uid());

drop policy if exists "Users can register one vendor profile" on public.vendor_profiles;
create policy "Users can register one vendor profile"
on public.vendor_profiles for insert to authenticated
with check (
  user_id = auth.uid()
  and status = 'pending'
  and verified = false
);

drop policy if exists "Vendors can update their own profile" on public.vendor_profiles;
create policy "Vendors can update their own profile"
on public.vendor_profiles for update to authenticated
using (user_id = auth.uid())
with check (user_id = auth.uid());

drop policy if exists "Anyone can browse approved products" on public.products;
create policy "Anyone can browse approved products"
on public.products for select to anon, authenticated
using (
  approval_status = 'approved'
  and is_available = true
  and public.is_public_vendor(vendor_id)
);

drop policy if exists "Vendors can view their own products" on public.products;
create policy "Vendors can view their own products"
on public.products for select to authenticated
using (
  exists (
    select 1
    from public.vendor_profiles vendor
    where vendor.id = products.vendor_id
      and vendor.user_id = auth.uid()
  )
);

drop policy if exists "Approved vendors can add products" on public.products;
create policy "Approved vendors can add products"
on public.products for insert to authenticated
with check (
  approval_status = 'approved'
  and exists (
    select 1
    from public.vendor_profiles vendor
    where vendor.id = products.vendor_id
      and vendor.user_id = auth.uid()
      and vendor.status = 'active'
      and vendor.verified = true
  )
);

drop policy if exists "Vendors can update their own products" on public.products;
create policy "Vendors can update their own products"
on public.products for update to authenticated
using (
  exists (
    select 1
    from public.vendor_profiles vendor
    where vendor.id = products.vendor_id
      and vendor.user_id = auth.uid()
  )
)
with check (
  exists (
    select 1
    from public.vendor_profiles vendor
    where vendor.id = products.vendor_id
      and vendor.user_id = auth.uid()
  )
);

drop policy if exists "Vendors can delete their own products" on public.products;
create policy "Vendors can delete their own products"
on public.products for delete to authenticated
using (
  exists (
    select 1
    from public.vendor_profiles vendor
    where vendor.id = products.vendor_id
      and vendor.user_id = auth.uid()
  )
);

