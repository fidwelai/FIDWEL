-- FIDWEL marketplace foundation
--
-- Apply this through the Supabase CLI or the SQL editor before relying on the
-- client-side flows. It establishes the ownership rule used by the app:
-- products.vendor_id always points to vendor_profiles.id, never auth.users.id.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  role text not null default 'customer'
    check (role in ('customer', 'vendor', 'agent', 'admin')),
  full_name text,
  phone text,
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists public.vendor_profiles (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references auth.users (id) on delete cascade,
  business_name text not null,
  phone text,
  description text,
  state text,
  lga text,
  town text,
  address text,
  status text not null default 'pending'
    check (status in ('pending', 'active', 'suspended', 'rejected')),
  verified boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  vendor_id uuid not null references public.vendor_profiles (id) on delete cascade,
  category_id bigint references public.categories (id) on delete set null,
  name text not null,
  description text,
  price numeric(12, 2) not null check (price > 0),
  unit text not null,
  quantity_available numeric(12, 2) not null default 0 check (quantity_available >= 0),
  image_url text,
  is_available boolean not null default true,
  approval_status text not null default 'approved'
    check (approval_status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- These ALTER statements make the migration safe for the tables already used
-- by the application. Review any existing product.vendor_id column before
-- applying if it currently stores auth.users IDs.
alter table public.products
  add column if not exists approval_status text not null default 'approved'
    check (approval_status in ('pending', 'approved', 'rejected'));
alter table public.products
  add column if not exists is_available boolean not null default true;

create index if not exists products_vendor_id_idx on public.products (vendor_id);
create index if not exists products_public_listing_idx
  on public.products (approval_status, is_available, category_id);
create index if not exists vendor_profiles_user_id_idx on public.vendor_profiles (user_id);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function public.create_profile_for_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, role, full_name, phone, avatar_url)
  values (
    new.id,
    case
      when new.raw_user_meta_data ->> 'account_type' = 'vendor' then 'vendor'
      else 'customer'
    end,
    nullif(new.raw_user_meta_data ->> 'full_name', ''),
    nullif(new.raw_user_meta_data ->> 'phone', ''),
    nullif(new.raw_user_meta_data ->> 'avatar_url', '')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

create or replace function public.protect_profile_role()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if auth.uid() is not null and new.role is distinct from old.role then
    raise exception 'Only an administrator can change an account role';
  end if;
  return new;
end;
$$;

create or replace function public.protect_vendor_moderation_fields()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if auth.uid() is not null and (
    new.user_id is distinct from old.user_id
    or new.status is distinct from old.status
    or new.verified is distinct from old.verified
  ) then
    raise exception 'Vendor verification is managed by FIDWEL';
  end if;
  return new;
end;
$$;

create or replace function public.protect_product_moderation_fields()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if auth.uid() is not null and (
    new.vendor_id is distinct from old.vendor_id
    or new.approval_status is distinct from old.approval_status
  ) then
    raise exception 'Product ownership and review status are managed by FIDWEL';
  end if;
  return new;
end;
$$;

-- RLS policies run as the querying user. This helper deliberately runs with
-- definer rights so anonymous shoppers can verify the vendor's public status
-- without gaining access to vendor contact or address fields.
create or replace function public.is_public_vendor(vendor_profile_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.vendor_profiles
    where id = vendor_profile_id
      and status = 'active'
      and verified = true
  );
$$;

