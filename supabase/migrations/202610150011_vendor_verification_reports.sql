create table if not exists public.vendor_verification_reports (
  id bigint generated by default as identity primary key,
  vendor_id uuid not null references public.vendor_profiles (id) on delete cascade,
  agent_id uuid not null references auth.users (id) on delete restrict,
  identity_confirmed boolean not null,
  location_confirmed boolean not null,
  products_confirmed boolean not null,
  recommendation text not null
    check (recommendation in ('approve', 'follow_up', 'reject')),
  notes text not null default '',
  review_status text not null default 'pending'
    check (review_status in ('pending', 'reviewed')),
  admin_notes text,
  reviewed_by uuid references auth.users (id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  constraint vendor_verification_reports_notes_length
    check (char_length(notes) <= 2000),
  constraint vendor_verification_reports_admin_notes_length
    check (admin_notes is null or char_length(admin_notes) <= 2000)
);

create index if not exists vendor_verification_reports_agent_created_idx
  on public.vendor_verification_reports (agent_id, created_at desc);
create index if not exists vendor_verification_reports_review_status_idx
  on public.vendor_verification_reports (review_status, created_at desc);

alter table public.vendor_verification_reports enable row level security;

drop policy if exists "Agents can view their verification reports"
  on public.vendor_verification_reports;
create policy "Agents can view their verification reports"
on public.vendor_verification_reports for select to authenticated
using (agent_id = auth.uid());

drop policy if exists "Admins can view all verification reports"
  on public.vendor_verification_reports;
create policy "Admins can view all verification reports"
on public.vendor_verification_reports for select to authenticated
using (public.is_admin());

grant select on public.vendor_verification_reports to authenticated;
grant usage, select on sequence public.vendor_verification_reports_id_seq
  to authenticated;
