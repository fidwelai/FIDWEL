-- FIDWEL orders foundation
--
-- Apply this after 202610150001_foundation.sql. It adds the checkout data
-- model used by the customer cart and the upcoming Paystack checkout flow.
--
-- Ownership rule carried over from the foundation migration: order_items
-- snapshot the vendor_profiles.id that owns each product so vendors can later
-- be granted access to the orders that contain their listings. Orders and
-- order_items keep a copy of name/price at purchase time so historic orders do
-- not change when a vendor edits or removes a product.

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references auth.users (id) on delete restrict,
  status text not null default 'pending'
    check (status in ('pending', 'paid', 'processing', 'shipped', 'delivered', 'cancelled', 'refunded')),
  payment_status text not null default 'unpaid'
    check (payment_status in ('unpaid', 'paid', 'failed', 'refunded')),
  payment_provider text not null default 'paystack',
  payment_reference text,
  currency text not null default 'NGN',
  subtotal numeric(12, 2) not null default 0 check (subtotal >= 0),
  delivery_fee numeric(12, 2) not null default 0 check (delivery_fee >= 0),
  total numeric(12, 2) not null default 0 check (total >= 0),
  contact_name text,
  contact_phone text,
  delivery_state text,
  delivery_lga text,
  delivery_town text,
  delivery_address text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders (id) on delete cascade,
  product_id bigint references public.products (id) on delete set null,
  vendor_id uuid references public.vendor_profiles (id) on delete set null,
  product_name text not null,
  unit text not null,
  unit_price numeric(12, 2) not null check (unit_price >= 0),
  quantity numeric(12, 2) not null check (quantity > 0),
  line_total numeric(12, 2) not null check (line_total >= 0),
  created_at timestamptz not null default now()
);

create index if not exists orders_customer_id_idx on public.orders (customer_id);
create index if not exists orders_status_idx on public.orders (status);
create index if not exists order_items_order_id_idx on public.order_items (order_id);
create index if not exists order_items_vendor_id_idx on public.order_items (vendor_id);

-- Order status and payment fields are driven by FIDWEL and the payment
-- provider. When a signed-in user edits an order (for example to correct a
-- delivery address) these fields must stay untouched. The service role used by
-- the Paystack webhook has no auth.uid() and can still update them.
create or replace function public.protect_order_financials()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if auth.uid() is not null and (
    new.status is distinct from old.status
    or new.payment_status is distinct from old.payment_status
    or new.payment_reference is distinct from old.payment_reference
    or new.payment_provider is distinct from old.payment_provider
    or new.total is distinct from old.total
    or new.subtotal is distinct from old.subtotal
    or new.delivery_fee is distinct from old.delivery_fee
    or new.customer_id is distinct from old.customer_id
  ) then
    raise exception 'Order status, totals, and payment are managed by FIDWEL';
  end if;
  return new;
end;
$$;

drop trigger if exists orders_set_updated_at on public.orders;
create trigger orders_set_updated_at
before update on public.orders
for each row execute function public.set_updated_at();

drop trigger if exists orders_financials_protected on public.orders;
create trigger orders_financials_protected
before update on public.orders
for each row execute function public.protect_order_financials();

alter table public.orders enable row level security;
alter table public.order_items enable row level security;

drop policy if exists "Customers can view their own orders" on public.orders;
create policy "Customers can view their own orders"
on public.orders for select to authenticated
using (customer_id = auth.uid());

drop policy if exists "Customers can create their own orders" on public.orders;
create policy "Customers can create their own orders"
on public.orders for insert to authenticated
with check (
  customer_id = auth.uid()
  and status = 'pending'
  and payment_status = 'unpaid'
);

drop policy if exists "Customers can update their own orders" on public.orders;
create policy "Customers can update their own orders"
on public.orders for update to authenticated
using (customer_id = auth.uid())
with check (customer_id = auth.uid());

drop policy if exists "Customers can view their own order items" on public.order_items;
create policy "Customers can view their own order items"
on public.order_items for select to authenticated
using (
  exists (
    select 1
    from public.orders o
    where o.id = order_items.order_id
      and o.customer_id = auth.uid()
  )
);

drop policy if exists "Customers can create items for their own orders" on public.order_items;
create policy "Customers can create items for their own orders"
on public.order_items for insert to authenticated
with check (
  exists (
    select 1
    from public.orders o
    where o.id = order_items.order_id
      and o.customer_id = auth.uid()
      and o.status = 'pending'
  )
);

grant select, insert, update on public.orders to authenticated;
grant select, insert on public.order_items to authenticated;
